import java.util.*;

public class variables {
    public static void main(String[] args) {
        // Variables
        int a = 25;
        int b = 10;
        int sum = a + b;
        int diff = a - b;
        System.out.println("a + b =" + sum);
        System.out.println("a - b =" + diff);
        int mul = a * b;
        System.out.println("a x b=" + mul);

    }
}
